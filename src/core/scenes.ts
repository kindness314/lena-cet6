/** 16 幕基础剧情 + 后续扩写幕（scenes-extra.ts），顺序决定每日轮换。 */
export const SCENES: Scene[] = [...BASE_SCENES, ...EXTRA_SCENES];

const SCENE_MAP = new Map(SCENES.map((scene) => [scene.id, scene]));
const ARC_MAP = new Map(ARCS.map((arc) => [arc.id, arc]));

export function sceneById(id: string | undefined): Scene | undefined {
  return id ? SCENE_MAP.get(id) : undefined;
}

export function arcById(id: ArcId): Arc {
  return ARC_MAP.get(id) ?? ARCS[0];
}

export function dayOrdinal(day: string): number {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(day);
  if (!match) return 0;
  const [year, month, date] = match.slice(1).map(Number);
  if (!year || !month || !date) return 0;
  return Math.floor(Date.UTC(year, month - 1, date) / 86_400_000);
}

export function defaultSceneForDay(day: string): Scene {
  const n = dayOrdinal(day);
  const index = ((n % SCENES.length) + SCENES.length) % SCENES.length;
  return SCENES[index];
}

export function sceneForState(
  state: Pick<State, "storySceneId"> & { words?: State["words"] },
  day: string,
): Scene {
  const manual = sceneById(state.storySceneId);
  if (manual) return manual;
  const n = dayOrdinal(day);
  const base = ((n % SCENES.length) + SCENES.length) % SCENES.length;
  const learned = state.words;
  if (learned) {
    // 当日池已经学完时顺延到下一个还有词的幕，避免剧情某天没有新词
    for (let k = 0; k < SCENES.length; k++) {
      const scene = SCENES[(base + k) % SCENES.length];
      if (scene.theme.some((w) => learned[w] === undefined)) return scene;
    }
  }
  return SCENES[base];
}

/** idx 超过当日拍数时 clamp 在末拍；负索引（异常状态）落到开场。 */
export function beatIndex(index: number, beatCount: number): number {
  if (beatCount <= 0) return 0;
  if (index < 0) return 0;
  return Math.min(index, beatCount - 1);
}

export function sceneBeat(scene: Scene, index: number): Beat {
  return scene.beats[beatIndex(index, scene.beats.length)] ?? scene.beats[0];
}

function fill(template: string, word: string): string {
  return template.replace(/\{w\}/g, word);
}

/** 答题页文案：旁白 + 出题话术，把当前词织进剧情。 */
export function sceneQuestion(scene: Scene, index: number, word: string): { narr: string; prompt: string } {
  const beat = sceneBeat(scene, index);
  return { narr: beat.narr, prompt: fill(beat.prompt, word) };
}

/** 结果页文案：答对/答错的剧情回应。 */
export function sceneFeedback(scene: Scene, index: number, word: string, correct: boolean): string {
  const beat = sceneBeat(scene, index);
  return fill(correct ? beat.good : beat.miss, word);
}

/** 结局文案：按今天的正确率分档（≥70% 走圆满收尾；一题没答也走温和收尾）。 */
export function sceneEnding(scene: Scene, answered: number, correctCount: number): string {
  if (answered > 0 && correctCount * 10 >= answered * 7) return scene.endGood;
  return scene.endSoft;
}
